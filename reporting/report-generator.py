import csv
import sys
import os
from datetime import datetime
from collections import Counter, defaultdict

# SLA Resolution Targets in Hours (Simulated Corporate Policy)
SLA_TARGETS_HOURS = {
    'P1': 4.0,     # Critical: 4 hours (24x7)
    'P2': 8.0,     # High: 8 business hours
    'P3': 72.0,    # Medium: 3 business days (72 hours)
    'P4': 120.0    # Low: 5 business days (120 hours)
}

DISCLAIMER_HEADER = [
    "*" * 75,
    "  [SIMULATED DATASET] NEXORA TECHNOLOGIES IT OPERATIONS LAB",
    "  NOTE: Fictional learning lab data - not actual production metrics.",
    "*" * 75,
]

def resolve_path(relative_path):
    """Resolve path relative to repo root."""
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base_dir, relative_path)

def load_incidents(filepath=None):
    """Load and parse incidents CSV file."""
    if filepath is None:
        filepath = resolve_path('incidents/incident-register.csv')
    
    if not os.path.exists(filepath):
        print(f"Error: Incident register not found at {filepath}", file=sys.stderr)
        return []
    
    incidents = []
    with open(filepath, mode='r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            clean_row = {k.strip(): v.strip() for k, v in row.items()}
            incidents.append(clean_row)
    return incidents

def load_service_requests(filepath=None):
    """Load and parse service requests CSV file."""
    if filepath is None:
        filepath = resolve_path('incidents/service-requests.csv')
    
    if not os.path.exists(filepath):
        return []
    
    requests = []
    with open(filepath, mode='r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            clean_row = {k.strip(): v.strip() for k, v in row.items()}
            requests.append(clean_row)
    return requests

def generate_daily_summary(incidents):
    """Generate Daily Service Desk Summary Report."""
    total = len(incidents)
    status_counts = Counter(inc.get('Status', 'Unknown') for inc in incidents)
    priority_counts = Counter(inc.get('Priority', 'Unknown') for inc in incidents)
    
    open_tickets = sum(status_counts[s] for s in ['New', 'InProgress', 'Escalated', 'OnHold'])
    resolved_tickets = status_counts.get('Resolved', 0)
    closed_tickets = status_counts.get('Closed', 0)
    
    lines = list(DISCLAIMER_HEADER)
    lines.extend([
        "=" * 75,
        "   NEXORA TECHNOLOGIES - IT SERVICE DESK DAILY SUMMARY",
        f"   Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} IST",
        "=" * 75,
        f"Total Logged Incidents:       {total}",
        f"Active Open / Backlog:        {open_tickets} ({(open_tickets/total*100 if total else 0.0):.1f}%)",
        f"Resolved Incidents:           {resolved_tickets} ({(resolved_tickets/total*100 if total else 0.0):.1f}%)",
        f"Closed Incidents:             {closed_tickets} ({(closed_tickets/total*100 if total else 0.0):.1f}%)",
        "-" * 75,
        "INCIDENTS BY PRIORITY (IMPACT x URGENCY):",
    ])
    for p in ['P1', 'P2', 'P3', 'P4']:
        count = priority_counts.get(p, 0)
        pct = (count / total * 100) if total else 0.0
        lines.append(f"  {p} - {count:2d} ({pct:5.1f}%)")
    
    lines.append("-" * 75)
    lines.append("INCIDENTS BY CURRENT LIFECYCLE STATUS:")
    for st in ['New', 'InProgress', 'OnHold', 'Escalated', 'Resolved', 'Closed']:
        if st in status_counts:
            lines.append(f"  {st:<15}: {status_counts[st]:2d} ({(status_counts[st]/total*100 if total else 0.0):.1f}%)")
            
    lines.append("=" * 75)
    return "\n".join(lines)

def generate_priority_report(incidents):
    """Generate Incident Priority Distribution Report."""
    total = len(incidents)
    priority_counts = Counter(inc.get('Priority', 'Unknown') for inc in incidents)
    
    lines = list(DISCLAIMER_HEADER)
    lines.extend([
        "=" * 75,
        "   NEXORA TECHNOLOGIES - TICKET PRIORITY BREAKDOWN",
        "=" * 75,
        f"{'Priority':<10}{'Severity':<15}{'Target Resolution':<22}{'Count':<8}{'Share':<8}",
        "-" * 75
    ])
    labels = {
        'P1': ('Critical', '4 Hours'),
        'P2': ('High', '8 Business Hours'),
        'P3': ('Medium', '3 Business Days'),
        'P4': ('Low', '5 Business Days')
    }
    for p in ['P1', 'P2', 'P3', 'P4']:
        count = priority_counts.get(p, 0)
        pct = (count / total * 100) if total else 0.0
        sev, target = labels.get(p, ('Unknown', 'N/A'))
        lines.append(f"{p:<10}{sev:<15}{target:<22}{count:<8}{pct:>5.1f}%")
    lines.append("-" * 75)
    lines.append(f"Total Evaluated Incidents: {total}")
    lines.append("=" * 75)
    return "\n".join(lines)

def generate_sla_report(incidents):
    """
    Generate SLA Compliance Report with strict ITIL methodology.
    Distinguishes resolved ticket performance from in-flight backlog.
    """
    total_incidents = len(incidents)
    
    # Priority buckets: resolved_met, resolved_breached, open_breached, open_in_flight
    p_data = defaultdict(lambda: {'total': 0, 'res_met': 0, 'res_breached': 0, 'open_breached': 0, 'open_pending': 0})
    
    for inc in incidents:
        p = inc.get('Priority', 'Unknown')
        status = inc.get('Status', 'Unknown')
        slam = inc.get('SLAMet', '').strip().lower()
        res_hours_str = inc.get('ResolutionTime_Hours', '').strip()
        
        p_data[p]['total'] += 1
        is_resolved = status in ['Resolved', 'Closed']
        
        if is_resolved:
            # Check numerical hours if available, otherwise check SLAMet
            if res_hours_str:
                try:
                    res_hours = float(res_hours_str)
                    target = SLA_TARGETS_HOURS.get(p, 72.0)
                    if res_hours <= target:
                        p_data[p]['res_met'] += 1
                    else:
                        p_data[p]['res_breached'] += 1
                except ValueError:
                    if slam in ['yes', 'true', '1']:
                        p_data[p]['res_met'] += 1
                    else:
                        p_data[p]['res_breached'] += 1
            else:
                if slam in ['yes', 'true', '1']:
                    p_data[p]['res_met'] += 1
                else:
                    p_data[p]['res_breached'] += 1
        else:
            # Active/Escalated/Open tickets
            if slam in ['no', 'false', '0']:
                p_data[p]['open_breached'] += 1
            else:
                p_data[p]['open_pending'] += 1

    lines = list(DISCLAIMER_HEADER)
    lines.extend([
        "=" * 75,
        "   NEXORA TECHNOLOGIES - SERVICE LEVEL AGREEMENT (SLA) REPORT",
        "=" * 75,
        f"{'Priority':<10}{'Target':<10}{'Total':<7}{'Res Met':<10}{'Res Breach':<12}{'Open Breach':<13}{'Compliance %':<12}",
        "-" * 75
    ])
    
    tot_all = 0
    tot_res_met = 0
    tot_res_brk = 0
    tot_opn_brk = 0
    
    for p in ['P1', 'P2', 'P3', 'P4']:
        d = p_data[p]
        tot = d['total']
        rm = d['res_met']
        rb = d['res_breached']
        ob = d['open_breached']
        
        tot_all += tot
        tot_res_met += rm
        tot_res_brk += rb
        tot_opn_brk += ob
        
        target_str = f"{int(SLA_TARGETS_HOURS[p])}h"
        
        # Overall compliance treats unresolved past-SLA tickets as breached
        met_count = rm
        pct = (met_count / tot * 100) if tot else 100.0
        lines.append(f"{p:<10}{target_str:<10}{tot:<7}{rm:<10}{rb:<12}{ob:<13}{pct:>10.1f}%")
        
    lines.append("-" * 75)
    overall_pct = (tot_res_met / tot_all * 100) if tot_all else 100.0
    lines.append(f"{'OVERALL':<20}{tot_all:<7}{tot_res_met:<10}{tot_res_brk:<12}{tot_opn_brk:<13}{overall_pct:>10.1f}%")
    lines.append("=" * 75)
    
    # Detailed breakdown notes
    total_resolved = tot_res_met + tot_res_brk
    res_compliance = (tot_res_met / total_resolved * 100) if total_resolved else 100.0
    lines.extend([
        "STATISTICAL INTERPRETATION:",
        f"  * Resolved Tickets Evaluated:         {total_resolved}",
        f"  * Resolution SLA on Resolved Tickets:  {res_compliance:.1f}% ({tot_res_met} of {total_resolved} met)",
        f"  * Active Backlog Breaches:            {tot_opn_brk} (Tickets escalated / pending L2/L3)",
        f"  * Total Portfolio SLA Rate:           {overall_pct:.1f}% ({tot_res_met} of {tot_all} tickets compliant)",
        "=" * 75
    ])
    return "\n".join(lines)

def generate_category_report(incidents):
    """Generate Category and Subcategory Analysis Report."""
    cat_counts = Counter(inc.get('Category', 'Unknown') for inc in incidents)
    cat_resolved = defaultdict(int)
    cat_times = defaultdict(list)
    
    for inc in incidents:
        c = inc.get('Category', 'Unknown')
        if inc.get('Status') in ['Resolved', 'Closed']:
            cat_resolved[c] += 1
        res_str = inc.get('ResolutionTime_Hours', '').strip()
        if res_str:
            try:
                cat_times[c].append(float(res_str))
            except ValueError:
                pass

    lines = list(DISCLAIMER_HEADER)
    lines.extend([
        "=" * 75,
        "   NEXORA TECHNOLOGIES - INCIDENT CATEGORY ANALYSIS",
        "=" * 75,
        f"{'Category':<18}{'Total':<8}{'Resolved':<10}{'Resolve Rate':<15}{'Avg Resolution':<15}",
        "-" * 75
    ])
    for c, total in sorted(cat_counts.items(), key=lambda x: x[1], reverse=True):
        res = cat_resolved[c]
        rate = (res / total * 100) if total else 0.0
        times = cat_times[c]
        avg_time = (sum(times) / len(times)) if times else 0.0
        lines.append(f"{c:<18}{total:<8}{res:<10}{rate:>11.1f}%   {avg_time:>9.2f} hrs")
        
    lines.append("=" * 75)
    return "\n".join(lines)

def generate_weekly_mis(incidents, service_requests=None):
    """Generate Weekly Management Information System (MIS) Report."""
    if service_requests is None:
        service_requests = []
        
    total_inc = len(incidents)
    total_sr = len(service_requests)
    
    group_counts = Counter(inc.get('AssignmentGroup', 'Unassigned') for inc in incidents)
    dept_counts = Counter(inc.get('Department', 'General') for inc in incidents)
    
    # Calculate Mean Time to Resolve (MTTR) strictly over resolved incidents
    res_times = []
    for inc in incidents:
        if inc.get('Status') in ['Resolved', 'Closed']:
            val = inc.get('ResolutionTime_Hours', '').strip()
            if val:
                try:
                    res_times.append(float(val))
                except ValueError:
                    pass
    avg_res_time = (sum(res_times) / len(res_times)) if res_times else 0.0
    
    # Escalation metrics
    escalated_count = sum(1 for inc in incidents if inc.get('Status') == 'Escalated' or inc.get('EscalatedTo', '').strip() not in ['', '—', '-'])
    fcr_count = sum(1 for inc in incidents if inc.get('Status') in ['Resolved', 'Closed'] and inc.get('EscalatedTo', '').strip() in ['', '—', '-'])
    fcr_rate = (fcr_count / total_inc * 100) if total_inc else 0.0

    lines = list(DISCLAIMER_HEADER)
    lines.extend([
        "=" * 75,
        "   NEXORA TECHNOLOGIES - WEEKLY IT SERVICE DESK MIS REPORT",
        f"   Reporting Period: November 2024 (Consolidated Month-End)",
        "=" * 75,
        "EXECUTIVE SUMMARY:",
        f"  Total IT Interactions Logged:      {total_inc + total_sr}",
        f"  Total Incident Tickets:            {total_inc}",
        f"  Total Service Requests:            {total_sr}",
        f"  Mean Time to Resolve (MTTR):       {avg_res_time:.2f} hours (Over {len(res_times)} resolved incidents)",
        f"  First Contact Resolution (FCR):    {fcr_rate:.1f}% ({fcr_count} resolved at L1)",
        f"  Total Escalated to L2/L3:          {escalated_count} ({(escalated_count/total_inc*100 if total_inc else 0.0):.1f}%)",
        "-" * 75,
        "INCIDENTS BY ASSIGNMENT GROUP:",
    ])
    for grp, cnt in group_counts.most_common():
        lines.append(f"  {grp:<30}: {cnt:2d} ({(cnt/total_inc*100 if total_inc else 0.0):.1f}%)")
        
    lines.append("-" * 75)
    lines.append("INCIDENTS BY IMPACTED DEPARTMENT:")
    for dept, cnt in dept_counts.most_common():
        lines.append(f"  {dept:<30}: {cnt:2d} ({(cnt/total_inc*100 if total_inc else 0.0):.1f}%)")
        
    lines.append("=" * 75)
    return "\n".join(lines)

def main():
    args = sys.argv[1:]
    command = "all"
    save_reports = False
    
    if "--save" in args:
        save_reports = True
        args.remove("--save")
        
    if args:
        command = args[0].lower()
        
    incidents = load_incidents()
    service_requests = load_service_requests()
    
    if not incidents:
        print("No incident data found to analyze.")
        sys.exit(1)
        
    reports = {
        'daily': ("daily-report.txt", generate_daily_summary(incidents)),
        'priority': ("priority-report.txt", generate_priority_report(incidents)),
        'sla': ("sla-report.txt", generate_sla_report(incidents)),
        'category': ("category-report.txt", generate_category_report(incidents)),
        'weekly': ("weekly-report.txt", generate_weekly_mis(incidents, service_requests))
    }
    
    if command == "all":
        for name, (filename, content) in reports.items():
            print(content)
            print("\n")
            if save_reports:
                out_path = resolve_path(os.path.join('reporting/reports', filename))
                with open(out_path, 'w', encoding='utf-8') as f:
                    f.write(content)
                print(f"[Saved] {out_path}")
    elif command in reports:
        filename, content = reports[command]
        print(content)
        if save_reports:
            out_path = resolve_path(os.path.join('reporting/reports', filename))
            with open(out_path, 'w', encoding='utf-8') as f:
                f.write(content)
            print(f"\n[Saved] {out_path}")
    else:
        print(f"Unknown command: '{command}'. Valid options: daily, priority, sla, category, weekly, all")
        sys.exit(1)

if __name__ == '__main__':
    main()
